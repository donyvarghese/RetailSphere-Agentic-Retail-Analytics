
import retail_agent


def test_total_revenue():
    result = retail_agent.get_total_revenue()

    expected = 184000.0
    actual = result["total_revenue"]

    assert actual == expected, (
        f"Expected ₹{expected}, but got ₹{actual}"
    )

    print("PASS: Total revenue calculation")


def test_top_products():
    result = retail_agent.get_top_products(3)

    expected_products = ["Laptop", "Mobile", "Headphones"]
    actual_products = [
        product["product_name"] for product in result
    ]

    assert actual_products == expected_products, (
        f"Expected {expected_products}, got {actual_products}"
    )

    print("PASS: Top 3 products")


def test_revenue_contribution():
    result = retail_agent.get_top_products_revenue_contribution(3)

    expected = 92.39
    actual = result["revenue_contribution_percentage"]

    assert actual == expected, (
        f"Expected {expected}%, got {actual}%"
    )

    print("PASS: Revenue contribution calculation")


def test_invalid_product_limit():
    try:
        retail_agent.execute_tool(
            "get_top_products",
            {"limit": 100}
        )
    except ValueError:
        print("PASS: Invalid product limit rejected")
        return

    raise AssertionError("Invalid product limit was accepted")


def test_unauthorized_tool():
    try:
        retail_agent.execute_tool(
            "delete_customer_data",
            {}
        )
    except ValueError:
        print("PASS: Unauthorized tool rejected")
        return

    raise AssertionError("Unauthorized tool was accepted")




def test_agent_tool_selection():

    question = "What is the total revenue generated by the business?"

    answer = retail_agent.run_agent(question)

    expected_tool = "get_total_revenue"

    actual_tools = retail_agent.last_tool_calls

    assert expected_tool in actual_tools, (
        f"Expected {expected_tool}, but got {actual_tools}"
    )

    assert "184000" in answer.replace(",", ""), (
        f"Expected revenue of 184000 in answer, got: {answer}"
    )

    print("PASS: LLM selected the correct tool")
    print("PASS: Agent returned the expected revenue")



def test_multiple_tool_selections():

    test_cases = [
        {
            "question": "Show me the top 3 products by revenue.",
            "expected_tool": "get_top_products"
        },
        {
            "question": "Which Indian state generated the highest revenue?",
            "expected_tool": "get_state_revenue"
        },
        {
            "question": "Show me monthly revenue.",
            "expected_tool": "get_monthly_revenue"
        },
        {
            "question": "What percentage of revenue came from the top 3 products?",
            "expected_tool": "get_top_products_revenue_contribution"
        }
    ]

    passed = 0

    for case in test_cases:

        print("\nTesting:", case["question"])

        retail_agent.run_agent(case["question"])

        actual_tools = retail_agent.last_tool_calls
        expected_tool = case["expected_tool"]

        if expected_tool in actual_tools:
            print("PASS:", expected_tool)
            passed += 1
        else:
            print("FAIL: Expected", expected_tool)
            print("Actual:", actual_tools)

    print("\nMulti-question evaluation:")
    print(f"{passed}/{len(test_cases)} passed")

    return passed, len(test_cases)




